#!/bin/sh
# Writes api/unimplemented_gen.go, the 501 fallback for operations no module serves yet.
set -eu
cd "$(dirname "$0")/.."
out=api/unimplemented_gen.go
{
  echo "// Code generated by scripts/gen-unimplemented.sh. DO NOT EDIT."
  echo
  echo "package api"
  echo
  echo "import ("
  echo "	\"net/http\""
  echo
  echo "	\"github.com/thev1ndu/workspacenow/wsn-service/internal/oapi\""
  echo ")"
  echo
  echo "// unimplemented answers every operation with 501 until a module serves it."
  echo "type unimplemented struct{}"
  echo
  awk '/^type ServerInterface interface/{f=1;next} f&&/^}/{f=0} f&&/\(w http.ResponseWriter/' internal/oapi/gen.go |
    sed -E 's/^[[:space:]]+//; s/ ([a-z][A-Za-z0-9]*) ([A-Z][A-Za-z0-9]*)([,)])/ \1 oapi.\2\3/g' |
    while IFS= read -r sig; do
      echo "func (unimplemented) $sig { notImplemented(w, r) }"
      echo
    done
} >"$out"
gofmt -w "$out"
echo "wrote $out"
