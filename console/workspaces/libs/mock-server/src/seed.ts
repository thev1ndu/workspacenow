const f = (name: string, label: string, type: EntityField["type"], extra: Partial<EntityField> = {}): EntityField => ({
  name,
  label,
  type,
  ...extra,
});

function entity(e: Omit<Entity, "version" | "lifecycle" | "updatedAt">, updatedAt: string): Entity {
  return { ...e, version: 1, lifecycle: "released", updatedAt };
}

function rec(id: string, entityName: string, values: Record<string, FieldValue>, at: string, by = "Seed import"): EntityRecord {
  return { id, entity: entityName, values, createdAt: at, updatedAt: at, createdBy: by };
}

function op(
  id: string,
  apiId: string,
  method: ApiOperation["method"],
  path: string,
  summary: string,
  businessOperation: string,
  permission: Permission,
  mcp?: { toolName: string; description: string; enabled: boolean },
): ApiOperation {
  return { id, apiId, method, path, summary, businessOperation, permission, rateLimitPerMinute: 300, mcp };
}

