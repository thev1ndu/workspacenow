#!/bin/sh
# Writes api/unimplemented_gen.go: the 501 fallback for exactly the operations no module
set -eu
cd "$(dirname "$0")/.."
out=api/unimplemented_gen.go

# Methods implemented by module handlers, e.g. "func (h *Handler) ListAgents(w http.ResponseWriter, ...".
implemented=$(mktemp)
trap 'rm -f "$implemented"' EXIT
grep -oE '[a-z]+API[[:space:]]+=[[:space:]]+[a-z]+\.[A-Za-z]+' api/server.go | awk '{print $3}' | cut -d. -f1 |
  while read -r pkg; do
    grep -rhoE 'func \([^)]*\) [A-Za-z0-9_]+\(w http\.ResponseWriter' "internal/$pkg" 2>/dev/null || true
  done |
  sed -E 's/.*\) ([A-Za-z0-9_]+)\(w http\.ResponseWriter/\1/' | sort -u > "$implemented"

body=$(mktemp)
trap 'rm -f "$implemented" "$body"' EXIT
awk '/^type ServerInterface interface/{f=1;next} f&&/^}/{f=0} f&&/\(w http.ResponseWriter/' internal/oapi/gen.go |
  sed -E 's/^[[:space:]]+//; s/ ([a-z][A-Za-z0-9]*) ([A-Z][A-Za-z0-9]*)([,)])/ \1 oapi.\2\3/g' |
  while IFS= read -r sig; do
    method=$(printf '%s' "$sig" | sed -E 's/^([A-Za-z0-9_]+)\(w.*/\1/')
    if grep -qx "$method" "$implemented"; then
      continue
    fi
    echo "func (unimplemented) $sig { notImplemented(w, r) }"
    echo
  done > "$body"

{
  echo "// Code generated by scripts/gen-unimplemented.sh. DO NOT EDIT."
  echo "// Regenerate after changing module handlers or internal/oapi; only operations no"
  echo "// module serves are emitted, so this file is empty when the contract is fully covered."
  echo
  echo "package api"
  if [ -s "$body" ]; then
    echo
    echo "import ("
    echo "	\"net/http\""
    echo
    echo "	\"github.com/thev1ndu/workspacenow/wsn-service/internal/oapi\""
    echo ")"
  fi
  echo
  echo "// unimplemented answers every operation no module serves with 501."
  echo "type unimplemented struct{}"
  echo
  cat "$body"
} >"$out"
gofmt -w "$out"
n=$(grep -c 'func (unimplemented)' "$out" || true)
echo "wrote $out ($n unimplemented operations)"
